class ImportBatch(TimeStampedModel):
    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        COMPLETED = "completed", "Completed"
        FAILED = "failed", "Failed"
        PARTIAL = "partial", "Partial"

    filename = models.CharField(max_length=255)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.PENDING)
    total_rows = models.PositiveIntegerField(default=0)
    imported_rows = models.PositiveIntegerField(default=0)
    updated_rows = models.PositiveIntegerField(default=0)
    skipped_rows = models.PositiveIntegerField(default=0)
    failed_rows = models.PositiveIntegerField(default=0)
    error_message = models.TextField(blank=True)
    column_mapping = models.JSONField(default=dict, blank=True)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="import_batches",
    )

    class Meta:
        ordering = ["-created_at", "-id"]
        verbose_name_plural = "import batches"

    def __str__(self) -> str:
        return f"{self.filename} - {self.status}"


class ImportRowIssue(models.Model):
    """One validation problem found on one spreadsheet row."""

    class Level(models.TextChoices):
        ERROR = "error", "Error"
        WARNING = "warning", "Warning"

    batch = models.ForeignKey(ImportBatch, on_delete=models.CASCADE, related_name="issues")
    row_number = models.PositiveIntegerField()
    column = models.CharField(max_length=100, blank=True)
    level = models.CharField(max_length=10, choices=Level.choices, default=Level.ERROR)
    code = models.CharField(max_length=50, blank=True)
    message = models.TextField()

    class Meta:
        ordering = ["row_number", "id"]

    def __str__(self) -> str:
        return f"row {self.row_number}: {self.message}"


