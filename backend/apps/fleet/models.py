"""Relational model for the driver income / fleet finance system.

Design rules that this file follows:

* No dashboard KPI is stored. Totals, margins and ratios are computed by the
  aggregation services in ``apps.fleet.services`` using ORM aggregation.
* The two exceptions are ``DailyEarning.total_income`` and
  ``PayrollSettlement.balance``. These are *row-level* derived values, not KPIs,
  and they are database-generated columns so that the database — not Python and
  never JavaScript — is the single source of truth. They can also be filtered,
  ordered and aggregated on directly.
* All money is ``Decimal`` with two decimal places.
"""

from __future__ import annotations

from decimal import Decimal

from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models
from django.db.models import F

ZERO = Decimal("0.00")


def money_field(**kwargs) -> models.DecimalField:
    """A consistent money column: 12 digits, 2 decimals, non-negative."""
    kwargs.setdefault("max_digits", 12)
    kwargs.setdefault("decimal_places", 2)
    kwargs.setdefault("default", ZERO)
    kwargs.setdefault("validators", [MinValueValidator(ZERO)])
    return models.DecimalField(**kwargs)


class TimeStampedModel(models.Model):
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        abstract = True


