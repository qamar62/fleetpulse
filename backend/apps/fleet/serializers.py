class PayrollSettlementSerializer(serializers.ModelSerializer):
    driver_name = serializers.CharField(source="driver.name", read_only=True)
    balance = serializers.DecimalField(max_digits=14, decimal_places=2, read_only=True)
    total_deductions = serializers.DecimalField(
        max_digits=14, decimal_places=2, read_only=True
    )
    period_label = serializers.SerializerMethodField()
    formula = serializers.SerializerMethodField()

    class Meta:
        model = PayrollSettlement
        fields = [
            "id", "driver", "driver_name", "period", "period_label",
            "salary", "advance", "other_deductions", "rent", "paid_amount",
            "total_deductions", "balance", "formula", "notes",
            "created_at", "updated_at",
        ]
        read_only_fields = ["balance", "created_at", "updated_at"]

    def get_period_label(self, obj) -> str:
        return obj.period.strftime("%B %Y")

    def get_formula(self, obj) -> str:
        return "balance = salary − advance − other_deductions − rent − paid_amount"

    def validate_period(self, value):
        # Always normalise to the first day of the month.
        return first_of_month(value)


