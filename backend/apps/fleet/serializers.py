class DailyEarningSerializer(serializers.ModelSerializer):
    driver_name = serializers.CharField(source="driver.name", read_only=True)
    vehicle_name = serializers.SerializerMethodField()
    vehicle_plate = serializers.CharField(source="vehicle.plate_number", read_only=True)
    total_income = serializers.DecimalField(
        max_digits=14, decimal_places=2, read_only=True,
        help_text="Generated by the database as the sum of the platform columns, cash included.",
    )
    platform_income = serializers.SerializerMethodField(
        help_text="The same total with cash taken out. Cash is not counted as income by default.",
    )
    status = serializers.SerializerMethodField()
    platform_shares = serializers.SerializerMethodField()

    class Meta:
        model = DailyEarning
        fields = [
            "id", "date", "driver", "driver_name", "vehicle", "vehicle_name", "vehicle_plate",
            *settings.INCOME_PLATFORMS,
            "total_income", "platform_income", "platform_shares", "status", "notes",
            "source_batch", "created_at", "updated_at",
        ]
        read_only_fields = [
            "total_income", "platform_income", "source_batch", "created_at", "updated_at",
        ]

    def get_vehicle_name(self, obj) -> str:
        return str(obj.vehicle)

    def get_platform_income(self, obj) -> Decimal:
        return quantize((obj.total_income or ZERO) - (obj.cash or ZERO))

    def get_status(self, obj) -> str:
        """Whether any money at all was recorded, cash included.

        This answers "did someone fill this row in", which is a different
        question from "does this row count towards income" - so it stays fixed
        while the cash toggle moves. A row that is pure cash is recorded, not
        missing.
        """
        return "recorded" if (obj.total_income or ZERO) > 0 else "no_income"

    def get_platform_shares(self, obj) -> dict:
        total = obj.total_income or ZERO
        return {name: pct(getattr(obj, name), total) for name in settings.INCOME_PLATFORMS}

    def validate(self, attrs):
        instance = self.instance
        date = attrs.get("date", getattr(instance, "date", None))
        driver = attrs.get("driver", getattr(instance, "driver", None))
        vehicle = attrs.get("vehicle", getattr(instance, "vehicle", None))

        if date and driver and vehicle:
            clash = DailyEarning.objects.filter(date=date, driver=driver, vehicle=vehicle)
            if instance:
                clash = clash.exclude(pk=instance.pk)
            if clash.exists():
                raise serializers.ValidationError(
                    {"date": "An entry already exists for this date, driver and vehicle."}
                )

        if vehicle and driver and vehicle.assigned_driver_id and vehicle.assigned_driver_id != driver.id:
            # Not fatal — fleets do swap cars — but the client should know.
            self.context.setdefault("warnings", []).append(
                f"{vehicle} is assigned to {vehicle.assigned_driver}, not {driver}."
            )
        return attrs


